/**
 * 서로 짝인 문서. privacy·email에는 전환할 상대가 없다.
 *
 * 이용약관 2종만 서로를 가리키므로 "그룹은 2개"를 전제로 짠다 — getTermsCounterpart가
 * 상대를 하나만 돌려주는 것이 그 전제다. 3개 이상으로 늘릴 일이 생기면 반환 타입부터 고쳐야 한다.
 */
const TERMS_SWITCH_GROUP: TermsDocumentId[] = ["service", "business"];

/**
 * 전환 UI가 가리킬 상대 문서. 그룹 밖의 문서(privacy·email)는 null이다.
 *
 * 상대의 본문이 아직 비어 있어도(versions: []) 그대로 돌려준다 — 버튼을 막지 않고
 * 이동한 화면에서 "이 문서는 준비 중입니다" 안내를 보게 하는 것이 이 화면의 규칙이다.
 */
export function getTermsCounterpart(id: TermsDocumentId): TermsDocument | null {
  if (!TERMS_SWITCH_GROUP.includes(id)) return null;
  const counterpartId = TERMS_SWITCH_GROUP.find((item) => item !== id);
  return termsDocuments.find((doc) => doc.id === counterpartId) ?? null;
}

