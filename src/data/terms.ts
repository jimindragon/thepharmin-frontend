import { parseKoDate } from "@/data/businessBilling";

/**
 * 약관·정책 문서의 본문과 버전 이력.
 *
 * 타입을 types/로 빼지 않고 데이터와 같은 파일에 둔다 — resources.ts와 같은 방식이다.
 * 이 파일은 본문만 담는다. 화면(라우트·컴포넌트)은 다음 단계다.
 */

export type TermsDocumentId = "service" | "business" | "privacy" | "email";

/** 목 — 가. 나. 다. */
export interface TermsSubItem {
  text: string;
}

/** 호 — 1. 2. 3. */
export interface TermsItem {
  text: string;
  subItems?: TermsSubItem[];
}

/** 항 — ① ② ③ */
export interface TermsParagraph {
  text: string;
  items?: TermsItem[];
}

/** 조 */
export interface TermsArticle {
  no: number;
  title: string;
  paragraphs: TermsParagraph[];
}

/** 장 */
export interface TermsChapter {
  no: number;
  title: string;
  articles: TermsArticle[];
}

export interface TermsVersion {
  /** "YYYY.MM.DD" — 결제 내역(businessBilling.ts)과 같은 표기. */
  effectiveDate: string;
  chapters: TermsChapter[];
  addendum: { title: string; paragraphs: string[] };
}

export interface TermsDocument {
  id: TermsDocumentId;
  title: string;
  path: string;
  /** 빈 배열 = 본문 준비 중. getEffectiveVersion이 null을 돌려준다. */
  versions: TermsVersion[];
}

/**
 * 항·목 마커는 데이터에 적지 않고 렌더 단계에서 인덱스로 붙인다 —
 * 본문에 기호가 섞이면 조항을 넣고 빼는 순간 번호가 어긋난다.
 */
export const CIRCLED_NUMBERS = ["①", "②", "③", "④", "⑤", "⑥", "⑦", "⑧", "⑨", "⑩"];
export const KOREAN_ORDINALS = ["가", "나", "다", "라", "마", "바", "사", "아", "자", "차"];

/**
 * 마커 파생 규칙
 *
 * - 항 마커(①②③)는 article.paragraphs.length > 1일 때만 붙인다. 문단이 하나뿐인 조는
 *   원문에도 마커가 없다(제1조·제26조가 그 형태다).
 * - 호 마커(1. 2. 3.)와 목 마커(가. 나. 다.)는 개수와 무관하게 항상 붙인다.
 * - 부칙은 마커 없는 문단이라 chapters 밖에 addendum으로 분리했다. TermsArticle에 넣으면
 *   위 규칙이 걸려 ①②가 잘못 붙는다.
 */

/**
 * 오늘 기준으로 효력이 있는 버전.
 *
 * upcoming: true — 아직 시행 전인 버전을 미리 보여주는 상태. 화면에서 "○년 ○월 ○일 시행 예정"
 * 같은 안내를 붙일지는 다음 단계에서 정한다.
 *
 * 기준일은 MOCK_TODAY_DATE다. 실제 시계(new Date())는 이 리포의 금지 사항이다(config/mockToday.ts).
 */
export function getEffectiveVersion(
  doc: TermsDocument,
  today: Date = MOCK_TODAY_DATE,
): { version: TermsVersion; upcoming: boolean } | null {
  if (doc.versions.length === 0) return null;

  const dated = doc.versions.map((version) => ({ version, date: parseKoDate(version.effectiveDate) }));

  const applied = dated.filter((entry) => entry.date <= today);
  if (applied.length > 0) {
    const latest = applied.reduce((a, b) => (b.date > a.date ? b : a));
    return { version: latest.version, upcoming: false };
  }

  // 전부 미래 시행 — 가장 이른 것을 미리 보여준다.
  const earliest = dated.reduce((a, b) => (b.date < a.date ? b : a));
  return { version: earliest.version, upcoming: true };
}

