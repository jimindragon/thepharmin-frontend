/**
 * ≤760px 풀블리드 카드 목록 컨테이너.
 *
 * 목록을 감싼 셸(.sidebar-shell·.app-shell)이 좌우로 --shell-gutter/2씩 물러나 있으므로,
 * 그만큼 음수 마진으로 되밀면 카드가 화면 폭을 꽉 채운다. 두 셸의 거터 값이 같은 토큰이라
 * 마이페이지(본문 px-0)와 일반 페이지가 같은 한 줄을 공유한다.
 *
 * 카드 좌우 테두리는 각 카드의 flush 분기가 지우고, 카드 사이 선은 여기 divide-y가 그린다 —
 * 첫 카드 위·마지막 카드 아래에는 선이 생기지 않는다. 카드 사이 세로 리듬은 gap이 아니라
 * 카드 내부 패딩이 담당하므로 ≤760px에서 gap-0으로 접는다.
 *
 * 761px 이상은 종전 그대로(gap-3 카드 목록)라 데스크톱 렌더에는 영향이 없다.
 */
export const FLUSH_LIST_CLASS =
  "flex flex-col gap-3 max-[760px]:-mx-[calc(var(--shell-gutter)/2)] max-[760px]:gap-0 max-[760px]:divide-y max-[760px]:divide-[var(--color-border)]";

/**
 * ≤760px 풀블리드 **본문 섹션 카드**. 위 목록판과 같은 음수 마진을 쓰되, 목록이 아니라
 * 자기 완결적인 섹션 카드(공고 상세·기업 상세 본문)에 붙인다.
 *
 * 세 가지를 한 묶음으로 다룬다.
 *   1) -mx  — 셸이 물러난 만큼 되밀어 화면 폭을 채운다.
 *   2) border-x-0 — 화면 끝에 닿은 세로선은 테두리가 아니라 잘린 자국으로 읽힌다.
 *      위아래 선은 남긴다. 섹션 사이는 회색 배경 간격이 이미 갈라 주지만, 흰 블록의
 *      시작·끝을 1px로 확정해 두는 편이 긴 본문에서 경계가 흐려지지 않는다.
 *   3) px-6 — 좌우 패딩이 그대로 화면 여백이 되므로, 같은 화면의 h1·탭이 서 있는
 *      --shell-gutter/2(=24px, ≤760px) 선에 맞춘다. JobCard flush가 pl-6으로 맞춘 선과 같다.
 *
 * 붙이는 쪽의 기본 좌우 패딩은 변형 없는 유틸리티(px-7 등)로 남겨 둘 것 — 같은 축(px)이라
 * "변형 없는 유틸리티 < 변형 붙은 유틸리티"만 남아 Tailwind 출력 순서에 기대지 않는다.
 * p 단축형과 섞으면 그 보장이 깨지므로, p-6을 쓰던 자리는 px-6 py-6으로 축을 나눠 둔다.
 *
 * 761px 이상은 클래스가 하나도 적용되지 않아 데스크톱 렌더에 영향이 없다.
 */
export const FLUSH_SECTION_CLASS =
  "max-[760px]:-mx-[calc(var(--shell-gutter)/2)] max-[760px]:border-x-0 max-[760px]:px-6";

/**
 * ≤760px 풀블리드 **그리드 목록**. 위 FLUSH_LIST_CLASS의 그리드판이다 — 카드가 flex 한 줄이 아니라
 * 여러 열로 깔리는 목록(기업 상세 면접 후기·기업 리뷰·뉴스 탭)을 좁은 화면에서 1열 낱장 목록으로 접는다.
 *
 * 열 정의(grid-cols-*·gap)는 호출부가 그대로 갖고, 여기서는 ≤760px 변형만 얹는다. 클래스가 전부
 * 변형 붙은 유틸리티라 761px 이상에는 한 줄도 적용되지 않는다 — 데스크톱 렌더에 영향이 없다.
 *
 * 카드 쪽 손질까지 여기서 한다([&>*]). 카드마다 flush 프로퍼티를 뚫는 대신 목록이 자식을 직접
 * 눌러쓰는 이유는, 이 자리에 오는 카드가 후기 카드 한 종류가 아니기 때문이다 — 첫 칸에 작성 유도
 * 카드(CompanyReviewWriteCard)나 열람권 상태 카드(InterviewAccessStatusCard)가 서고, 뉴스 탭은
 * 아예 인라인 <a>다. 세 컴포넌트에 같은 프로퍼티를 각각 심는 것보다 목록 한 줄이 덜 침습적이다.
 *   - border-0 — 낱장 사이 선은 divide-y가 그린다. 화면 끝에 닿은 세로선은 잘린 자국으로 읽힌다.
 *   - px-6 — 카드 안쪽 좌우 패딩이 그대로 화면 여백이 되므로 같은 화면의 h1·탭이 선 24px에 맞춘다.
 *     세로 패딩은 카드가 쓰던 값을 그대로 둔다(p 단축형을 쓰는 카드도 자식 선택자 쪽이 이긴다).
 */
export const FLUSH_GRID_CLASS =
  "max-[760px]:-mx-[calc(var(--shell-gutter)/2)] max-[760px]:grid-cols-1 max-[760px]:gap-0 max-[760px]:divide-y max-[760px]:divide-[var(--color-border)] max-[760px]:[&>*]:border-0 max-[760px]:[&>*]:px-6";
